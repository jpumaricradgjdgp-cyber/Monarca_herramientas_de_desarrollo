SELECT e.tabla, e.columna,
       CASE
         WHEN t.table_name IS NULL THEN 'FALTA_TABLA'
         WHEN c.column_name IS NULL THEN 'FALTA_COLUMNA'
         WHEN c.data_type <> e.tipo_esperado THEN 'REVISAR_TIPO'
         WHEN e.requiere_no_nulo AND c.is_nullable = 'YES' THEN 'REVISAR_NULOS'
         ELSE 'OK'
       END AS resultado,
       e.tipo_esperado, c.data_type AS tipo_actual,
       e.requiere_no_nulo, c.is_nullable AS permite_nulos,
       c.character_maximum_length AS longitud_actual,
       c.numeric_precision AS precision_actual,
       c.numeric_scale AS decimales_actuales,
       c.is_identity, c.column_default
FROM esperadas e
LEFT JOIN information_schema.tables t
  ON t.table_schema = 'monarca' AND t.table_name = e.tabla
 AND t.table_type = 'BASE TABLE'
LEFT JOIN information_schema.columns c
  ON c.table_schema = 'monarca' AND c.table_name = e.tabla
 AND c.column_name = e.columna
ORDER BY resultado, e.tabla, e.columna;
